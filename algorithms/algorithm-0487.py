class Trie0487_0001:
    def __init__(self):
        self.children = {}
        self.terminal = False

    def insert(self, word):
        node = self
        for character in word:
            node = node.children.setdefault(character, Trie0487_0001())
        node.terminal = True

    def contains(self, word):
        node = self
